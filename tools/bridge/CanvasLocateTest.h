// 这里用**纯内存合成图**把判据固定下来：
//   · 两个同色不同大小的圆重叠   → 必须命中真值（±3px）
//   · 两个同色同大小的圆重叠     → 必须判为 ambiguous 并拒绝（不许猜）
//   · 孤立内容                   → 必须命中真值
//   · 被上层不透明块完全遮住     → 必须判失败（不许拿错位置补边）
// 定义在 BridgeApp.cpp（和定位实现同一个 TU，能直接用内部辅助函数）。
// ============================================================================

